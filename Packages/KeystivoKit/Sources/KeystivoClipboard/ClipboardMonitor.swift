import AppKit
import KeystivoCore
import Observation
import UniformTypeIdentifiers

nonisolated public struct ClipboardSettings: Codable, Hashable, Sendable {
    public var isEnabled = true
    public var maxItems = 500
    /// Days to keep unpinned items; nil keeps them until `maxItems` is reached.
    public var retentionDays: Int? = 30
    public var capturesImages = true
    public var capturesFiles = true
    /// Keep history only in memory (nothing written to disk).
    public var memoryOnly = false
    /// Paste immediately after choosing an item, instead of only copying.
    public var pastesDirectly = true
    /// Apps whose copies are never recorded.
    public var excludedBundleIDs: [String] = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
        "com.apple.keychainaccess", "com.apple.Passwords", "com.dashlane.dashlanephonefinal",
        "org.keepassxc.keepassxc", "com.lastpass.LastPass",
    ]

    public init() {}
}

/// Watches the general pasteboard and records history with privacy filters.
///
/// macOS has no pasteboard change notification; reading `changeCount` is a
/// cheap in-process check, done twice a second with timer tolerance so the
/// system can coalesce wakeups.
@Observable
public final class ClipboardMonitor {
    public static let shared = ClipboardMonitor()

    public var settings = ClipboardSettings() {
        didSet { if settings != oldValue { settingsChanged(from: oldValue) } }
    }
    public private(set) var isPaused = false
    /// Bumped whenever history changes so views can reload.
    public private(set) var revision = 0
    public private(set) var store: ClipboardStore?

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var ignoreChangeCount: Int?
    @ObservationIgnored private var skipNext = false

    /// Pasteboard markers used by password managers and well-behaved apps
    /// (see nspasteboard.org) to flag secrets and transient data.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    public init() {}

    public func start() {
        openStore()
        guard settings.isEnabled else { return }
        startTimer()
        Task { await prune() }
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func openStore() {
        do {
            store = settings.memoryOnly ? try ClipboardStore() : try ClipboardStore(url: AppPaths.clipboardDatabase)
        } catch {
            DiagnosticsCenter.shared.record(error, module: "Clipboard", context: L("clipboard.error.database"))
            store = try? ClipboardStore()
        }
    }

    private func startTimer() {
        timer?.invalidate()
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func settingsChanged(from old: ClipboardSettings) {
        if settings.memoryOnly != old.memoryOnly { openStore(); revision += 1 }
        if settings.isEnabled { if timer == nil { startTimer() } } else { stop() }
        Task { await prune() }
    }

    public func setPaused(_ paused: Bool) { isPaused = paused }

    /// The next copy will not be recorded (e.g. "copy password" flows).
    public func ignoreNextCopy() { skipNext = true }

    /// Call right after Keystivo itself writes to the pasteboard so the write
    /// is not recorded as a new history item.
    public func markOwnWrite() {
        let count = NSPasteboard.general.changeCount
        ignoreChangeCount = count
        lastChangeCount = count
    }

    // MARK: Capture

    private func check() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if let ignored = ignoreChangeCount, ignored == count { return }
        if skipNext { skipNext = false; return }
        guard !isPaused, settings.isEnabled else { return }

        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.privateTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, settings.excludedBundleIDs.contains(source) { return }
        guard let item = Self.makeItem(from: pasteboard, source: source, settings: settings) else { return }
        Task {
            do {
                try await store?.add(item)
                revision += 1
            } catch {
                DiagnosticsCenter.shared.record(error, module: "Clipboard")
            }
        }
    }

    static func makeItem(from pasteboard: NSPasteboard, source: String?, settings: ClipboardSettings) -> ClipboardItem? {
        if settings.capturesFiles,
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let names = urls.map(\.lastPathComponent).joined(separator: ", ")
            return ClipboardItem(kind: .file, text: names, filePaths: urls.map(\.path), sourceBundleID: source)
        }
        if settings.capturesImages, let image = NSImage(pasteboard: pasteboard), pasteboard.string(forType: .string) == nil,
           let png = image.downscaledPNG(maxDimension: 1600) {
            let size = image.size
            return ClipboardItem(kind: .image, text: "\(Int(size.width))×\(Int(size.height))", data: png, sourceBundleID: source)
        }
        if let color = NSColor(from: pasteboard) {
            return ClipboardItem(kind: .color, text: color.hexString, sourceBundleID: source)
        }
        guard let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        if let url = URL(string: string.trimmingCharacters(in: .whitespacesAndNewlines)), let scheme = url.scheme,
           ["http", "https", "mailto", "ftp"].contains(scheme.lowercased()), !string.contains("\n") {
            return ClipboardItem(kind: .url, text: string, sourceBundleID: source)
        }
        if let rtf = pasteboard.data(forType: .rtf), rtf.count < 2_000_000 {
            return ClipboardItem(kind: .richText, text: string, data: rtf, sourceBundleID: source)
        }
        return ClipboardItem(kind: .text, text: string, sourceBundleID: source)
    }

    // MARK: Using items

    /// Puts an item back on the pasteboard (without re-recording it).
    public func copy(_ item: ClipboardItem, plainText: Bool = false) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .file where !plainText:
            pasteboard.writeObjects(item.filePaths.map { URL(fileURLWithPath: $0) as NSURL })
        case .image where !plainText:
            if let data = item.data, let image = NSImage(data: data) { pasteboard.writeObjects([image]) }
        case .richText where !plainText:
            if let data = item.data { pasteboard.setData(data, forType: .rtf) }
            pasteboard.setString(item.text, forType: .string)
        case .url where !plainText:
            pasteboard.setString(item.text, forType: .string)
            pasteboard.setString(item.text, forType: .URL)
        default:
            pasteboard.setString(item.text, forType: .string)
        }
        ignoreChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        Task {
            try? await store?.touch(id: item.id)
            revision += 1
        }
    }

    /// Copies and pastes into the frontmost app (after the caller restored focus).
    public func paste(_ item: ClipboardItem, plainText: Bool = false) {
        copy(item, plainText: plainText)
        Task {
            try? await Task.sleep(for: .milliseconds(120))
            SyntheticInput.paste()
        }
    }

    public func items(matching query: String, kind: ClipboardKind? = nil, limit: Int = 200) async -> [ClipboardItem] {
        (try? await store?.items(matching: query, kind: kind, limit: limit)) ?? []
    }

    public func delete(_ item: ClipboardItem) async {
        try? await store?.delete(id: item.id)
        revision += 1
    }

    public func togglePin(_ item: ClipboardItem) async {
        try? await store?.setPinned(id: item.id, pinned: !item.isPinned)
        revision += 1
    }

    public func clearHistory(keepPinned: Bool = true) async {
        try? await store?.clear(keepPinned: keepPinned)
        revision += 1
    }

    public func prune() async {
        let age = settings.retentionDays.map { TimeInterval($0) * 86_400 }
        try? await store?.prune(maxItems: settings.maxItems, maxAge: age)
        revision += 1
    }
}

extension NSImage {
    /// PNG data scaled so the longest side is at most `maxDimension` points.
    func downscaledPNG(maxDimension: CGFloat) -> Data? {
        let longest = max(size.width, size.height)
        let scale = longest > maxDimension ? maxDimension / longest : 1
        let target = NSSize(width: max(1, size.width * scale), height: max(1, size.height * scale))
        guard let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: Int(target.width), pixelsHigh: Int(target.height),
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        ) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        draw(in: NSRect(origin: .zero, size: target), from: .zero, operation: .copy, fraction: 1)
        NSGraphicsContext.restoreGraphicsState()
        return rep.representation(using: .png, properties: [:])
    }
}

extension NSColor {
    var hexString: String {
        guard let rgb = usingColorSpace(.sRGB) else { return "#000000" }
        return String(format: "#%02X%02X%02X", Int(rgb.redComponent * 255), Int(rgb.greenComponent * 255), Int(rgb.blueComponent * 255))
    }
}
